// Tiny memos force constant replacement, and many boards per prover wrap the 3-bit stamp.  Neither
// may change any answer.
TEST(tie, memo) {
  Random random(6113);
  vector<high_board_t> boards;
  for (const int stones : {22, 24, 26, 28, 30})
    for (int i = 0; i < 6; i++) boards.push_back(random_position(random, stones));
  tie_prover_t tiny(2), small(8), shared;
  for (const auto& board : boards) {
    tie_prover_t fresh;
    const auto r = fresh.prove(board, 2, 1e9);
    for (tie_prover_t* p : {&tiny, &small, &shared}) {
      const auto s = p->prove(board, 2, 1e9);
      ASSERT_EQ(r.mover, s.mover) << board;
      ASSERT_EQ(r.other, s.other) << board;
    }
  }
}

// A timed out search never claims more than a complete one.  Checking the time at every node makes
// timeouts land everywhere in the search.
TEST(tie, timeout) {
  Random random(2203);
  tie_prover_t prover;
  prover.set_time_check_bits(0);
  int timeouts = 0;
  for (const int stones : {18, 20, 22}) {
    for (int i = 0; i < 6; i++) {
      const auto board = random_position(random, stones);
      const auto full = prover.prove(board, 2, 1e9);
      for (const double cap : {0.0, 1e-4, 1e-3}) {
        const auto r = prover.prove(board, 2, cap);
        timeouts += r.timeout;
        if (r.mover >= 0) {
          ASSERT_TRUE(full.mover >= 0 && full.mover <= r.mover) << board;
        }
        if (r.other >= 0) {
          ASSERT_TRUE(full.other >= 0 && full.other <= r.other) << board;
        }
      }
    }
  }
  PENTAGO_ASSERT_GT(timeouts, 10);
}

